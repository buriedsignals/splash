// The landing film's two house faces, written out as bytes.
//
// WHY THE BYTES AND NOT A LINK. A Remotion render runs in a headless browser with no guarantee that
// a network stylesheet has arrived before the first frame is painted, and a frame painted in the
// fallback face is a frame in the wrong typeface with nothing to say so. Embedded, the face is
// there before `FontFace.load()` is even called — see `film/load-typefaces.ts`, which blocks the
// render on it.
//
// WHY IT NO LONGER HAS ITS OWN FETCHER. This script used to read a stylesheet somebody had saved by
// hand into `gf.css` (a file that is in no checkout, so the script as committed could not be run),
// pull the URLs out with three regexes of its own, and `fetch()` them with no cache, no check that
// what came back was a font, and no check that it came from Google's own host. The web beats needed
// exactly those four steps, and wiring recopied per place drifts per place — so the steps are now
// `fetchWebFaces` in `shared/design-base/typefaces.mjs`, and this file only says WHICH faces the
// film wants. It shares the film's cache with every chart and map page in the repository.
//
// LATIN AND LATIN-EXT ONLY: the film's own words are English, and the front pages it draws are
// French, British, American and Swiss — every glyph of those is inside those two subsets.
//
// THE VARIABLE FILE, NOT A STATIC INSTANCE. `Script.tsx` sets 200 and 800 of the same family and
// `Wordmark.tsx` sets 800; asked for a weight RANGE, Google answers with one variable file per
// subset covering all of it, which is smaller than two instances and lets a weight be animated.
//
// Usage:  bun film/scripts/fetch-typefaces.mjs

import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { fetchWebFaces } from "#shared/design-base/typefaces.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(join(HERE, "..", "typefaces.ts"));

/** The two families, and the weight range each is asked for — the landing's own `--D` and `--C`. */
const WANTED = [
  { family: "Bricolage Grotesque", spec: "wght@200..800" },
  { family: "Space Grotesk", spec: "wght@300..700" },
];
const SUBSETS = ["latin", "latin-ext"];

const faces = [];
for (const { family, spec } of WANTED)
  for (const face of fetchWebFaces(family, { spec, keep: (f) => SUBSETS.includes(f.subset) })) {
    faces.push(face);
    console.error(`${face.family}|${face.subset}  ${face.bytes} bytes  <- ${face.url}`);
  }

// Sorted so a re-run produces the same file: Google lists its subsets in an order of its own, and a
// generated artefact that reshuffles is a diff nobody can read.
faces.sort((a, b) => a.family.localeCompare(b.family) || a.subset.localeCompare(b.subset));

const body = faces
  .map(
    (f) => `  {
    family: ${JSON.stringify(f.family)},
    subset: ${JSON.stringify(f.subset)},
    weight: ${JSON.stringify(f.weightTo > f.weight ? `${f.weight} ${f.weightTo}` : String(f.weight))},
    unicodeRange: ${JSON.stringify(f.unicodeRange)},
    // ${f.url}
    woff2: "${f.base64}",
  },`,
  )
  .join("\n");

writeFileSync(
  OUT,
  `// GENERATED by film/scripts/fetch-typefaces.mjs — do not edit by hand.
//
// The landing's two typefaces, carried as bytes rather than as a stylesheet link.
// A Remotion render runs in a headless browser with no guarantee that a network
// stylesheet has arrived before the first frame is painted, and a frame painted
// in the fallback face is a frame in the wrong typeface with nothing to say so.
// Embedded, the face is there before \`FontFace.load()\` is even called.
//
// Latin and latin-ext only: the film's own words are English, and the front
// pages it draws are French, British, American and Swiss — every glyph of those
// is inside those two subsets.

export type Typeface = {
  family: string;
  subset: string;
  weight: string;
  unicodeRange: string;
  woff2: string;
};

export const TYPEFACES: Typeface[] = [
${body}
];

/** The two families, by the role they play — the landing's own \`--D\` and \`--C\`. */
export const DISPLAY = "'Bricolage Grotesque', Helvetica, sans-serif";
export const COPY = "'Space Grotesk', Helvetica, sans-serif";
/** What a front page is set in — the hero's own \`SERIF\`, a system face on purpose. */
export const SERIF = "'Times New Roman', Times, Georgia, serif";
`,
);
console.error(`wrote ${OUT} — ${faces.length} faces`);
