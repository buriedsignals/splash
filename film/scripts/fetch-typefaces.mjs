import { writeFileSync, readFileSync } from "node:fs";
const css = readFileSync("gf.css", "utf8");
const want = [
  ["Bricolage Grotesque", "latin"],
  ["Bricolage Grotesque", "latin-ext"],
  ["Space Grotesk", "latin"],
  ["Space Grotesk", "latin-ext"],
];
const seen = new Set();
const faces = [];
for (const block of css.split("@font-face").slice(1)) {
  const family = /font-family: '([^']+)'/.exec(block)[1];
  const range = /unicode-range: ([^;]+);/.exec(block)[1];
  const url = /url\((https:[^)]+)\)/.exec(block)[1];
  const subset = range.startsWith("U+0000-00FF")
    ? "latin"
    : range.startsWith("U+0100")
      ? "latin-ext"
      : "other";
  const key = `${family}|${subset}`;
  if (!want.some(([f, s]) => f === family && s === subset)) continue;
  if (seen.has(key)) continue;
  seen.add(key);
  const bytes = Buffer.from(await (await fetch(url)).arrayBuffer());
  faces.push({ family, subset, range, url, base64: bytes.toString("base64"), bytes: bytes.length });
  console.error(`${key}  ${bytes.length} bytes  <- ${url}`);
}
const weights = { "Bricolage Grotesque": "200 800", "Space Grotesk": "300 700" };
const body = faces
  .map(
    (f) => `  {
    family: ${JSON.stringify(f.family)},
    subset: ${JSON.stringify(f.subset)},
    weight: ${JSON.stringify(weights[f.family])},
    unicodeRange: ${JSON.stringify(f.range)},
    // ${f.url}
    woff2: "${f.base64}",
  },`,
  )
  .join("\n");
writeFileSync(
  "/Users/rmdms/Sites/Professional/splash/film/typefaces.ts",
  `// GENERATED by film/scripts/fetch-typefaces.mjs — do not edit by hand.
//
// The landing's two typefaces, carried as bytes rather than as a stylesheet link.
// A Remotion render runs in a headless browser with no guarantee that a network
// stylesheet has arrived before the first frame is painted, and a frame painted
// in the fallback face is a frame in the wrong typeface with nothing to say so.
// Embedded, the face is there before \`FontFace.load()\` is even called.
//
// Latin and latin-ext only: the film's own words are English, and the front
// pages it draws are French, British, American and Swiss — every glyph of those
// is inside those two subsets.

export type Typeface = {
  family: string;
  subset: string;
  weight: string;
  unicodeRange: string;
  woff2: string;
};

export const TYPEFACES: Typeface[] = [
${body}
];

/** The two families, by the role they play — the landing's own \`--D\` and \`--C\`. */
export const DISPLAY = "'Bricolage Grotesque', Helvetica, sans-serif";
export const COPY = "'Space Grotesk', Helvetica, sans-serif";
/** What a front page is set in — the hero's own \`SERIF\`, a system face on purpose. */
export const SERIF = "'Times New Roman', Times, Georgia, serif";
`,
);
console.error(`wrote film/typefaces.ts — ${faces.length} faces`);
