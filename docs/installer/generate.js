// Pure function: (form config) -> bash string. No side effects, no network.
import { RUNTIMES } from "./runtimes.js";

export function scriptFilename() {
  return "atelier-setup.command";
}

const REPO_URL = "https://github.com/buriedsignals/atelier.git"; // confirm before public release

export function generateScript(config) {
  const rt = RUNTIMES[config.runtime];
  if (!rt) throw new Error(`unknown runtime: ${config.runtime}`);
  if (!rt.verified)
    throw new Error(`runtime not yet available: ${config.runtime}`);

  const k = config.keys ?? {};
  const embed = config.embed ?? {};
  const env = [
    `${rt.keyEnv}=${k.ai ?? ""}`,
    `VITE_MAPTILER_KEY=${k.maptiler ?? ""}`,
    `REMOTION_MAPTILER_KEY=${k.maptiler ?? ""}`,
    `DATAWRAPPER_API_TOKEN=${k.datawrapper ?? ""}`,
    `ATELIER_EMBED_APP=${embed.app ?? ""}`,
    `FLY_API_TOKEN=${embed.flyToken ?? ""}`,
  ].join("\n");

  return `#!/bin/bash
# atelier-setup.command — generated by the Atelier installer.
# This file contains your API keys. Delete this file after a successful run.
set -e

echo "-> Installing Atelier (this takes a few minutes)..."

if ! command -v brew >/dev/null 2>&1; then
  echo "-> Installing Homebrew..."
  /bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"
fi

if ! command -v bun >/dev/null 2>&1; then
  echo "-> Installing Bun..."
  brew install oven-sh/bun/bun
fi

if ! command -v ${rt.bin} >/dev/null 2>&1; then
  echo "-> Installing ${rt.label}..."
  ${rt.installCmd}
fi

if [ ! -d "$HOME/Atelier" ]; then
  echo "-> Downloading Atelier..."
  git clone ${REPO_URL} "$HOME/Atelier"
fi

echo "-> Installing the render engine (Playwright Chromium)..."
# Producers (chart-native, map-native) render with Playwright's Chromium — pre-install it
# so the first visual doesn't stall on a mid-run browser download.
( cd "$HOME/Atelier/skills/chart-native" && bun install >/dev/null 2>&1 && bunx playwright install chromium )

echo "-> Writing configuration..."
cat > "$HOME/Atelier/.env" <<'ATELIER_ENV'
${env}
ATELIER_ENV

if ! grep -q "${rt.keyEnv}" "$HOME/.zshrc" 2>/dev/null; then
  echo 'export ${rt.keyEnv}=${k.ai ?? ""}' >> "$HOME/.zshrc"
fi

echo ""
echo "Done! To launch Atelier, open Terminal and run:"
echo "    ${rt.launch}"
echo ""
echo "Security note: this file contains your keys. You can delete it now."
`;
}
