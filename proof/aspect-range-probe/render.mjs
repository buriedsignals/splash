// ASPECT-RANGE PROBE — at what plot aspect does each of these types still READ?
//
// `skills/chart-beat/scripts/type-at-size.mjs` refuses every tall frame for a type it has no
// MEASURED_ASPECT row for, and names the missing measurement as the reason. That refusal is honest
// and it is the wrong answer for five types this corpus already draws: `waterfall`, `slope`,
// `small-multiples`, `bump` and `population-pyramid`. This probe is the measurement it asks for.
// It also RE-measures `line`, whose recorded 0.8–1.8 was taken at 900x560 and at the earlier
// probe's frames, never at 16:9, while this corpus's own accepted landscape line measures 1.94:1.
//
// ── HOW THIS DIFFERS FROM `portrait-aspect-probe/portrait-probe.mjs` ──────────────────────────
//
// That probe derived a range from THREE points: it rendered the type's stretch arm at 900x560,
// 1920x1080 and 1080x1080 and took the extremes. Two things are wrong with three points as a
// method, and the file itself records the first: the 1080x1080 render "was itself already
// stretched", so the line's floor of 0.8 is the aspect of a picture nobody would publish, written
// down as if it were a bound. The second is that three accepted frames cannot bracket a bound they
// never straddle — the same file's 1.8 ceiling for a line is below this corpus's own accepted
// landscape line at 1.94:1.
//
// So this probe SWEEPS. For each type it holds the plot's WIDTH and the type size constant and
// varies the plot's HEIGHT, so aspect is the only thing that changes between two arms of the same
// type; every arm is written out as a PNG and a person opens it. The range recorded is where the
// geometry still reads, and `ASPECT-VERDICT.md` beside this file says what was seen at each arm.
// `ASPECT-MEASUREMENTS.md` is generated by this script and holds only what the instrument measured.
//
// ── WHAT IT DRAWS, AND WHAT IT DELIBERATELY DOES NOT ─────────────────────────────────────────
//
// The PLOT and the labels that live in it or against it — marks, gridlines, tick labels, category
// and series names, value labels. No title, no standfirst, no credit. That is not a shortcut: a
// `MEASURED_ASPECT` row is consumed by `assertPlotAspect`, which is handed the PLOT rectangle, and
// what the furniture above the plot costs is the removal ladder's question, not this one. Two
// separate measurements is exactly why the ladder exists as its own list.
//
// The GEOMETRY IS THE BEAT'S OWN. Every `*Geometry` function below is imported from the beat that
// ships that type, not re-derived here — a probe that re-implemented the scales would measure its
// own arithmetic. The DRAWING is this file's, because a beat's component is one block of frame,
// header, plot and credit, and only the plot is under test.
//
// Usage, from the repository root:  bun proof/aspect-range-probe/render.mjs
//                                   bun proof/aspect-range-probe/render.mjs --only line
//                                   bun proof/aspect-range-probe/render.mjs --aspects 1.9,2.1

