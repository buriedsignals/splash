//
// Plot WIDTH, and the type size. A landscape static's plot is ~1500px wide inside a 1920 frame and
// its floor is 26px (`sizes.mjs`, the article reference); 900px of plot at 26px type is the same
// ratio of type to plot and keeps a 0.5:1 arm's frame under 2,000px tall, which is a picture a
// person can actually open. What matters is that it does not vary: if the type or the width moved
// between arms, a difference the eye reported could not be attributed to the aspect.
//
// BOTH ARE KNOBS, and the second regime is not decoration. A range measured at one ratio of type to
// plot is only transferable if that ratio is the one the frame really gives: a square 1080 frame
