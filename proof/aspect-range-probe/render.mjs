const bold = (fontSize) => ({ fontSize, fontWeight: 700 });
const plain = (fontSize) => ({ fontSize, fontWeight: 400 });

function parseCsv(text) {
  const [header, ...rows] = text.trim().split(/\r?\n/);
  const cols = header.split(",");
  return rows
    .filter((r) => r.length > 0)
    .map((row) => {
      const cells = row.split(",");
      const rec = {};
      cols.forEach((c, i) => (rec[c] = cells[i]));
      return rec;
    });
}

const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function text(content, x, y, { fontSize, fontWeight = 400, fill, anchor = "start" }) {
  return (
    `<text x="${round(x)}" y="${round(y)}" font-family="${FONT_FAMILY}" font-size="${fontSize}" ` +
    `font-weight="${fontWeight}" fill="${fill}"` +
    (anchor === "start" ? "" : ` text-anchor="${anchor}"`) +
    `>${esc(content)}</text>`
  );
}

const round = (v) => Math.round(v * 10) / 10;

/** Words to lines, at a measured width — the same shape every beat here carries. */
function wrap(string, maxWidth, font) {
  const lines = [];
  let current = "";
  for (const word of String(string).split(/\s+/)) {
    const trial = current ? `${current} ${word}` : word;
    if (current && measureText(trial, font) > maxWidth) {
      lines.push(current);
      current = word;
    } else current = trial;
  }
  return current ? [...lines, current] : lines;
}

function page(body, width, height, ground) {
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" ` +
    `viewBox="0 0 ${width} ${height}">` +
    `<rect x="0" y="0" width="${width}" height="${height}" fill="${ground}"/>` +
    body.join("") +
    `</svg>`
  );
}

/** The frame a plot of `PLOT_W x (PLOT_W / aspect)` needs, given its own gutters. */
function frameFor(aspect, padding) {
  const plotH = PLOT_W / aspect;
  return {
    width: Math.round(PLOT_W + padding.left + padding.right),
    height: Math.round(plotH + padding.top + padding.bottom),
    plotW: PLOT_W,
    plotH,
  };
}

